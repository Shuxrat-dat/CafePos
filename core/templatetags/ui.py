@register.simple_tag
def icon(name, size=20, cls="", stroke=2):
    body = ICONS.get(name, ICONS["info"])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" width="{0}" height="{0}" viewBox="0 0 24 24" fill="none" '
        'stroke="currentColor" stroke-width="{1}" stroke-linecap="round" stroke-linejoin="round" '
        'class="shrink-0 {2}" aria-hidden="true">{3}</svg>',
        size, stroke, cls, mark_safe(body),
    )


@register.simple_tag
def illustration(kind, size=40):
    """Иконка категории на мягком цветном фоне: единый стиль для блюд без фотографии."""
    icon_name, bg, fg = ILLUSTRATIONS.get(kind or "", ILLUSTRATIONS["plate"])
